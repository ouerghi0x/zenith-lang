                sb.append("                .andExpect(result -> {\n");
                sb.append("                    int s = result.getResponse().getStatus();\n");
                sb.append("                    org.junit.jupiter.api.Assertions.assertTrue(s == 401 || s == 403, \"Expected 401 or 403 but got \" + s);\n");
