    private static JavaSourceFile generateFileValidationRules(String basePkg, String pkgDir) {
        String content = "package " + basePkg + ".storage;\n\n"
                + "import org.springframework.web.multipart.MultipartFile;\n"
                + "import java.util.List;\n\n"
                + "public class FileValidationRules {\n"
                + "    private final long maxSizeBytes;\n"
                + "    private final List<String> allowedTypes;\n"
                + "    private final String pathPrefix;\n\n"
                + "    public FileValidationRules(long maxSizeBytes, List<String> allowedTypes, String pathPrefix) {\n"
                + "        this.maxSizeBytes = maxSizeBytes;\n"
                + "        this.allowedTypes = allowedTypes != null ? allowedTypes : List.of();\n"
                + "        this.pathPrefix = pathPrefix != null ? pathPrefix : \"\";\n"
                + "    }\n\n"
                + "    public static FileValidationRules defaults() {\n"
                + "        return new FileValidationRules(50 * 1024 * 1024L, List.of(), \"uploads/\");\n"
                + "    }\n\n"
                + "    public static FileValidationRules forImage(String maxSizeStr, List<String> customTypes, String path) {\n"
                + "        long size = parseSize(maxSizeStr, 5 * 1024 * 1024L);\n"
                + "        List<String> types = (customTypes != null && !customTypes.isEmpty())\n"
                + "                ? customTypes\n"
                + "                : List.of(\"image/jpeg\", \"image/png\", \"image/webp\", \"image/gif\", \"image/svg+xml\");\n"
                + "        return new FileValidationRules(size, types, path != null ? path : \"images/\");\n"
                + "    }\n\n"
                + "    public static FileValidationRules forFile(String maxSizeStr, List<String> customTypes, String path) {\n"
                + "        long size = parseSize(maxSizeStr, 50 * 1024 * 1024L);\n"
                + "        return new FileValidationRules(size, customTypes != null ? customTypes : List.of(), path != null ? path : \"files/\");\n"
                + "    }\n\n"
                + "    public static long parseSize(String str, long defaultBytes) {\n"
                + "        if (str == null || str.isBlank()) return defaultBytes;\n"
                + "        String s = str.trim().toUpperCase();\n"
                + "        try {\n"
                + "            if (s.endsWith(\"KB\") || s.endsWith(\"K\")) {\n"
                + "                long num = Long.parseLong(s.replaceAll(\"[^0-9]\", \"\"));\n"
                + "                return num * 1024L;\n"
                + "            } else if (s.endsWith(\"MB\") || s.endsWith(\"M\")) {\n"
                + "                long num = Long.parseLong(s.replaceAll(\"[^0-9]\", \"\"));\n"
                + "                return num * 1024L * 1024L;\n"
                + "            } else if (s.endsWith(\"GB\") || s.endsWith(\"G\")) {\n"
                + "                long num = Long.parseLong(s.replaceAll(\"[^0-9]\", \"\"));\n"
                + "                return num * 1024L * 1024L * 1024L;\n"
                + "            } else {\n"
                + "                return Long.parseLong(s);\n"
                + "            }\n"
                + "        } catch (Exception e) {\n"
                + "            return defaultBytes;\n"
                + "        }\n"
                + "    }\n\n"
                + "    public void validate(MultipartFile file) {\n"
                + "        if (file == null || file.isEmpty()) {\n"
                + "            throw new FileValidationException(\"File must not be empty\");\n"
                + "        }\n"
                + "        if (file.getSize() > maxSizeBytes) {\n"
                + "            throw new FileValidationException(\"File size exceeds maximum limit of \" + (maxSizeBytes / (1024 * 1024)) + \" MB (actual: \" + (file.getSize() / 1024) + \" KB)\");\n"
                + "        }\n"
                + "        if (!allowedTypes.isEmpty()) {\n"
                + "            String ct = file.getContentType();\n"
                + "            if (ct == null || ct.isBlank()) {\n"
                + "                throw new FileValidationException(\"Could not determine file MIME type\");\n"
                + "            }\n"
                + "            boolean match = false;\n"
                + "            for (String allowed : allowedTypes) {\n"
                + "                if (\"*/*\".equals(allowed) || allowed.equalsIgnoreCase(ct)) {\n"
                + "                    match = true;\n"
                + "                    break;\n"
                + "                }\n"
                + "                if (allowed.endsWith(\"/*\")) {\n"
                + "                    String prefix = allowed.substring(0, allowed.indexOf('/'));\n"
                + "                    if (ct.toLowerCase().startsWith(prefix.toLowerCase() + \"/\")) {\n"
                + "                        match = true;\n"
                + "                        break;\n"
                + "                    }\n"
                + "                }\n"
                + "            }\n"
                + "            if (!match) {\n"
                + "                throw new FileValidationException(\"File type '\" + ct + \"' is not permitted. Allowed types: \" + String.join(\", \", allowedTypes));\n"
                + "            }\n"
                + "        }\n"
                + "    }\n\n"
                + "    public long getMaxSizeBytes() { return maxSizeBytes; }\n"
                + "    public List<String> getAllowedTypes() { return allowedTypes; }\n"
                + "    public String getPathPrefix() { return pathPrefix; }\n"
                + "}\n";
        return new JavaSourceFile(pkgDir + "storage/FileValidationRules.java", content);
    }

