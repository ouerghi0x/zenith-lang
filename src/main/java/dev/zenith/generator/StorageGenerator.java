    public static List<JavaSourceFile> generate(ZenithFile file) {
        List<JavaSourceFile> list = new ArrayList<>();
        String basePkg = file.getConfig().getPackage();
        String basePath = file.getConfig().getBasePath();
        String pkgDir = "src/main/java/" + basePkg.replace('.', '/') + "/";

        list.add(generateStorageProvider(basePkg, pkgDir));
        list.add(generateMinioStorageProvider(basePkg, pkgDir));
        list.add(generateS3StorageProvider(basePkg, pkgDir));
        list.add(generateStorageProperties(basePkg, pkgDir));
        list.add(generateStorageConfig(basePkg, pkgDir));
        list.add(generateFileValidationException(basePkg, pkgDir));
        list.add(generateFileValidationRules(basePkg, pkgDir));
        list.add(generateFileResource(basePkg, pkgDir));
        list.add(generateFileMetadata(basePkg, pkgDir));
        list.add(generateFileMetadataRepository(basePkg, pkgDir));
        list.add(generateFileMetadataResponse(basePkg, pkgDir));
        list.add(generateStorageService(basePkg, pkgDir));
        list.add(generateStorageServiceImpl(basePkg, pkgDir));
        list.add(generateFileStorageController(basePkg, pkgDir, basePath, file.hasAuth()));

        return list;
    }

