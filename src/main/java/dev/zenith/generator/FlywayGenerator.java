package dev.zenith.generator;

import dev.zenith.ast.*;

import java.util.ArrayList;
import java.util.List;

public class FlywayGenerator {

    public static JavaSourceFile generate(ZenithFile file) {
        StringBuilder sb = new StringBuilder();
        sb.append("-- =============================================================================\n");
        sb.append("-- Database Schema Migration generated by Zenith DSL\n");
        sb.append("-- Target: PostgreSQL / H2 (ANSI SQL compliant)\n");
        sb.append("-- =============================================================================\n\n");

        List<String> foreignKeyStatements = new ArrayList<>();
        List<String> indexStatements = new ArrayList<>();

        // 1. Create Tables
        for (ModelDef model : file.getModels()) {
            String tableName = TypeHelper.toSnakeCase(TypeHelper.pluralize(model.getName()));
            sb.append("-- Table: ").append(tableName).append("\n");
            sb.append("CREATE TABLE IF NOT EXISTS ").append(tableName).append(" (\n");

            List<String> colDefs = new ArrayList<>();
            for (FieldDef field : model.getFields()) {
                String colName = TypeHelper.toSnakeCase(field.getName());
                StringBuilder colDef = new StringBuilder("    ").append(colName).append(" ");

                if (field.hasAnnotation("id")) {
                    if ("UUID".equalsIgnoreCase(field.getType().getName())) {
                        colDef.append("UUID PRIMARY KEY");
                    } else {
                        colDef.append("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
                    }
                } else {
                    colDef.append(toSqlType(field));
                    if (!field.isOptional()) {
                        colDef.append(" NOT NULL");
                    }
                    if (field.hasAnnotation("unique")) {
                        colDef.append(" UNIQUE");
                    }
                }
                colDefs.add(colDef.toString());

                // Indexes for unique or search fields
                if (field.hasAnnotation("unique") && !field.hasAnnotation("id")) {
                    indexStatements.add("CREATE INDEX IF NOT EXISTS idx_" + tableName + "_" + colName + " ON " + tableName + " (" + colName + ");");
                }
            }

            // Foreign key columns for ManyToOne / OneToOne relations
            for (RelationDef rel : model.getRelations()) {
                if (rel.getRelationType() == RelationType.MANY_TO_ONE || rel.getRelationType() == RelationType.ONE_TO_ONE) {
                    String fkCol = TypeHelper.toSnakeCase(rel.getFieldName()) + "_id";
                    String fkSqlType = resolveTargetSqlIdType(rel.getTargetModel(), file);
                    StringBuilder colDef = new StringBuilder("    ").append(fkCol).append(" ").append(fkSqlType);
                    if (!rel.isOptional()) {
                        colDef.append(" NOT NULL");
                    }
                    colDefs.add(colDef.toString());

                    String targetTable = TypeHelper.toSnakeCase(TypeHelper.pluralize(rel.getTargetModel()));
                    String fkName = "fk_" + tableName + "_" + fkCol;
                    foreignKeyStatements.add("ALTER TABLE " + tableName + " ADD CONSTRAINT " + fkName + " FOREIGN KEY (" + fkCol + ") REFERENCES " + targetTable + " (id) ON DELETE SET NULL;");
                    indexStatements.add("CREATE INDEX IF NOT EXISTS idx_" + tableName + "_" + fkCol + " ON " + tableName + " (" + fkCol + ");");
                }
            }

            sb.append(String.join(",\n", colDefs));
            sb.append("\n);\n\n");

            // Crud search field indexes
            CrudConfig crud = model.getCrudConfig();
            if (crud != null) {
                for (String sf : crud.getSearchFields()) {
                    String col = TypeHelper.toSnakeCase(sf);
                    indexStatements.add("CREATE INDEX IF NOT EXISTS idx_" + tableName + "_" + col + " ON " + tableName + " (" + col + ");");
                }
            }
        }

        // 2. Many-to-Many Join Tables
        for (ModelDef model : file.getModels()) {
            String tableName = TypeHelper.toSnakeCase(TypeHelper.pluralize(model.getName()));
            for (RelationDef rel : model.getRelations()) {
                if (rel.getRelationType() == RelationType.MANY_TO_MANY) {
                    String targetTable = TypeHelper.toSnakeCase(TypeHelper.pluralize(rel.getTargetModel()));
                    String joinTable = tableName + "_" + TypeHelper.toSnakeCase(rel.getFieldName());
                    String col1 = TypeHelper.toSnakeCase(model.getName()) + "_id";
                    String col2 = TypeHelper.toSnakeCase(rel.getTargetModel()) + "_id";
                    String col1SqlType = resolveTargetSqlIdType(model.getName(), file);
                    String col2SqlType = resolveTargetSqlIdType(rel.getTargetModel(), file);

                    sb.append("-- Join Table: ").append(joinTable).append("\n");
                    sb.append("CREATE TABLE IF NOT EXISTS ").append(joinTable).append(" (\n");
                    sb.append("    ").append(col1).append(" ").append(col1SqlType).append(" NOT NULL,\n");
                    sb.append("    ").append(col2).append(" ").append(col2SqlType).append(" NOT NULL,\n");
                    sb.append("    PRIMARY KEY (").append(col1).append(", ").append(col2).append("),\n");
                    sb.append("    CONSTRAINT fk_").append(joinTable).append("_1 FOREIGN KEY (").append(col1).append(") REFERENCES ").append(tableName).append(" (id) ON DELETE CASCADE,\n");
                    sb.append("    CONSTRAINT fk_").append(joinTable).append("_2 FOREIGN KEY (").append(col2).append(") REFERENCES ").append(targetTable).append(" (id) ON DELETE CASCADE\n");
                    sb.append(");\n\n");
                }
            }
        }

        // 3. Foreign Keys
        if (!foreignKeyStatements.isEmpty()) {
            sb.append("-- =============================================================================\n");
            sb.append("-- Foreign Key Constraints\n");
            sb.append("-- =============================================================================\n");
            for (String fk : foreignKeyStatements) {
                sb.append(fk).append("\n");
            }
            sb.append("\n");
        }

        // 4. Indexes
        if (!indexStatements.isEmpty()) {
            sb.append("-- =============================================================================\n");
            sb.append("-- Indexes for High Performance Querying\n");
            sb.append("-- =============================================================================\n");
            for (String idx : indexStatements) {
                sb.append(idx).append("\n");
            }
            sb.append("\n");
        }

        return new JavaSourceFile("src/main/resources/db/migration/V1__initial_schema.sql", sb.toString());
    }

    private static String toSqlType(FieldDef field) {
        String typeName = field.getType().getName().toLowerCase();
        if (field.hasAnnotation("text")) return "TEXT";

        switch (typeName) {
            case "string":
                Object len = field.getType().getParams().get("length");
                if (len == null) len = field.getType().getParams().get("max");
                return len != null ? "VARCHAR(" + len + ")" : "VARCHAR(255)";
            case "int":
            case "integer":
                return "INTEGER";
            case "long":
                return "BIGINT";
            case "decimal":
            case "bigdecimal":
                Object prec = field.getType().getParams().get("precision");
                Object scale = field.getType().getParams().get("scale");
                if (prec != null && scale != null) {
                    return "NUMERIC(" + prec + ", " + scale + ")";
                }
                return "NUMERIC(19, 4)";
            case "double":
                return "DOUBLE PRECISION";
            case "bool":
            case "boolean":
                return "BOOLEAN";
            case "datetime":
            case "localdatetime":
                return "TIMESTAMP";
            case "date":
            case "localdate":
                return "DATE";
            case "uuid":
                return "UUID";
            default:
                return "VARCHAR(100)";
        }
    }

    private static String resolveTargetSqlIdType(String targetModelName, ZenithFile file) {
        for (ModelDef m : file.getModels()) {
            if (m.getName().equalsIgnoreCase(targetModelName)) {
                FieldDef idField = m.getIdField();
                if (idField != null && "UUID".equalsIgnoreCase(idField.getType().getName())) {
                    return "UUID";
                }
            }
        }
        return "BIGINT";
    }
}
