    private static JavaSourceFile generateStorageServiceImpl(String basePkg, String pkgDir) {
        String content = "package " + basePkg + ".storage.impl;\n\n"
                + "import " + basePkg + ".entity.FileMetadata;\n"
                + "import " + basePkg + ".exception.ResourceNotFoundException;\n"
                + "import " + basePkg + ".repository.FileMetadataRepository;\n"
                + "import " + basePkg + ".storage.FileResource;\n"
                + "import " + basePkg + ".storage.FileValidationRules;\n"
                + "import " + basePkg + ".storage.StorageProvider;\n"
                + "import " + basePkg + ".storage.StorageService;\n"
                + "import org.springframework.stereotype.Service;\n"
                + "import org.springframework.transaction.annotation.Transactional;\n"
                + "import org.springframework.web.multipart.MultipartFile;\n\n"
                + "import java.io.InputStream;\n"
                + "import java.security.MessageDigest;\n"
                + "import java.util.UUID;\n\n"
                + "@Service\n"
                + "@Transactional\n"
                + "public class StorageServiceImpl implements StorageService {\n\n"
                + "    private final StorageProvider storageProvider;\n"
                + "    private final FileMetadataRepository metadataRepository;\n\n"
                + "    public StorageServiceImpl(StorageProvider storageProvider, FileMetadataRepository metadataRepository) {\n"
                + "        this.storageProvider = storageProvider;\n"
                + "        this.metadataRepository = metadataRepository;\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public FileMetadata upload(MultipartFile file, FileValidationRules rules) {\n"
                + "        rules.validate(file);\n"
                + "        try {\n"
                + "            byte[] bytes = file.getBytes();\n"
                + "            MessageDigest digest = MessageDigest.getInstance(\"SHA-256\");\n"
                + "            byte[] hash = digest.digest(bytes);\n"
                + "            StringBuilder hex = new StringBuilder();\n"
                + "            for (byte b : hash) {\n"
                + "                String h = Integer.toHexString(0xff & b);\n"
                + "                if (h.length() == 1) hex.append('0');\n"
                + "                hex.append(h);\n"
                + "            }\n"
                + "            String checksum = hex.toString();\n\n"
                + "            String origName = file.getOriginalFilename() != null ? file.getOriginalFilename() : \"file\";\n"
                + "            String ext = \"\";\n"
                + "            int dot = origName.lastIndexOf('.');\n"
                + "            if (dot >= 0) ext = origName.substring(dot);\n\n"
                + "            String prefix = rules.getPathPrefix() != null ? rules.getPathPrefix() : \"uploads/\";\n"
                + "            if (!prefix.endsWith(\"/\") && !prefix.isEmpty()) prefix += \"/\";\n"
                + "            String fileKey = prefix + UUID.randomUUID() + ext;\n\n"
                + "            String contentType = file.getContentType() != null ? file.getContentType() : \"application/octet-stream\";\n"
                + "            try (InputStream is = file.getInputStream()) {\n"
                + "                storageProvider.upload(fileKey, is, file.getSize(), contentType);\n"
                + "            }\n\n"
                + "            FileMetadata meta = new FileMetadata(\n"
                + "                    fileKey,\n"
                + "                    origName,\n"
                + "                    contentType,\n"
                + "                    file.getSize(),\n"
                + "                    checksum,\n"
                + "                    storageProvider.getProviderName()\n"
                + "            );\n"
                + "            return metadataRepository.save(meta);\n"
                + "        } catch (Exception e) {\n"
                + "            if (e instanceof RuntimeException) throw (RuntimeException) e;\n"
                + "            throw new RuntimeException(\"Failed to upload file: \" + e.getMessage(), e);\n"
                + "        }\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public FileMetadata upload(MultipartFile file, String folder) {\n"
                + "        FileValidationRules rules = FileValidationRules.forFile(null, null, folder);\n"
                + "        return upload(file, rules);\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    @Transactional(readOnly = true)\n"
                + "    public FileResource download(String fileKey) {\n"
                + "        FileMetadata meta = metadataRepository.findByFileKey(fileKey)\n"
                + "                .orElseThrow(() -> new ResourceNotFoundException(\"File not found with key: \" + fileKey));\n"
                + "        InputStream is = storageProvider.download(fileKey);\n"
                + "        return new FileResource(is, meta.getContentType(), meta.getSize(), meta.getOriginalFilename());\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    @Transactional(readOnly = true)\n"
                + "    public FileMetadata getMetadata(String fileKey) {\n"
                + "        return metadataRepository.findByFileKey(fileKey)\n"
                + "                .orElseThrow(() -> new ResourceNotFoundException(\"File not found with key: \" + fileKey));\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public void delete(String fileKey) {\n"
                + "        if (fileKey == null || fileKey.isBlank()) return;\n"
                + "        try {\n"
                + "            if (storageProvider.exists(fileKey)) {\n"
                + "                storageProvider.delete(fileKey);\n"
                + "            }\n"
                + "        } catch (Exception ignored) {}\n"
                + "        metadataRepository.deleteByFileKey(fileKey);\n"
                + "    }\n\n"
                + "    @Override\n"
                + "    public String getUrl(String fileKey) {\n"
                + "        return storageProvider.getUrl(fileKey);\n"
                + "    }\n"
                + "}\n";
        return new JavaSourceFile(pkgDir + "storage/impl/StorageServiceImpl.java", content);
    }

